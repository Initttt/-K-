import { test, expect, type Page } from "@playwright/test";
import { mkdirSync, readFileSync } from "node:fs";
import path from "node:path";

const output = path.join(process.cwd(), "output", "playwright");
mkdirSync(output, { recursive: true });
const personalSpace = (page: Page) => page.getByRole("button", { name: "我的设备", exact: true });
async function addDevice(page: Page, name: string, price: string, category = "phone") {
  await page.getByRole("button", { name: "添加设备", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("设备名称").fill(name);
  await dialog.getByLabel("设备类别").selectOption(category);
  await dialog.getByLabel("品牌", { exact: false }).fill("测试品牌");
  await dialog.getByLabel("型号", { exact: false }).fill("Test Device 1");
  await dialog.getByLabel("配置", { exact: false }).fill("256GB");
  await dialog.getByLabel("购买日期").fill("2026-05-10");
  await dialog.getByLabel("购买价格").fill(price);
  await dialog.getByRole("button", { name: "确认并添加设备" }).click();
  await expect(page.getByRole("button", { name: `查看 ${name}`, exact: true })).toBeVisible();
}
async function closeDialog(page: Page) { await page.getByRole("dialog").getByRole("button", { name: "关闭弹窗" }).click(); }
async function openDetail(page: Page, name: string) { await page.getByRole("button", { name: `查看 ${name}`, exact: true }).click(); }

test("设备增改删、保存、手动区间估值、缺估值汇总、刷新与JSON恢复", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByText("给你的第一件装备一个位置")).toBeVisible();
  await addDevice(page, "日常手机", "8000");
  await expect(page.getByTestId("reference-total")).toContainText("等待第一笔估值");
  await page.reload();
  await openDetail(page, "日常手机");
  await expect(page.getByRole("dialog").getByText("暂无估值", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "填写参考估值" }).click();
  let dialog = page.getByRole("dialog");
  await dialog.getByLabel("参考值 / 区间下限").fill("5000");
  await dialog.getByLabel("区间上限").fill("6000");
  await dialog.getByLabel("数据日期").fill("2026-10-20");
  await dialog.getByLabel("来源说明").fill("测试时人工核对的参考区间");
  await dialog.getByRole("button", { name: "保存参考估值" }).click();
  await expect(page.getByRole("dialog").getByText(/当前仅有一个记录点/)).toBeVisible();
  await expect(page.getByText("超过七天，建议复核")).toBeVisible();
  await closeDialog(page);
  await addDevice(page, "尚未估值的平板", "2000", "tablet");
  await expect(page.getByTestId("purchase-total")).toContainText("10,000");
  await expect(page.getByTestId("reference-total")).toContainText("5,500");
  await expect(page.getByTestId("total-change")).toContainText("2,500");
  await openDetail(page, "日常手机");
  await page.getByRole("button", { name: "编辑设备", exact: true }).click();
  dialog = page.getByRole("dialog");
  await dialog.getByLabel("设备名称").fill("主力手机");
  await dialog.getByLabel("购买价格").fill("7000");
  await dialog.getByRole("button", { name: "保存修改" }).click();
  await expect(page.getByRole("dialog").getByRole("heading", { name: "主力手机" })).toBeVisible();
  await closeDialog(page);
  await page.reload();
  await expect(page.getByTestId("purchase-total")).toContainText("9,000");
  await expect(page.getByTestId("total-change")).toContainText("1,500");
  const before = await page.evaluate(() => localStorage.getItem("my-gear:v1:personal:CN:CNY"));
  await page.getByRole("button", { name: "刷新估值", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("没有可自动获取的新行情");
  expect(await page.evaluate(() => localStorage.getItem("my-gear:v1:personal:CN:CNY"))).toBe(before);
  await page.getByRole("button", { name: "设置与备份", exact: true }).click();
  const downloaded = page.waitForEvent("download");
  await page.getByRole("button", { name: "导出 JSON", exact: true }).click();
  const backupPath = path.join(output, "test-backup.json");
  await (await downloaded).saveAs(backupPath);
  expect(JSON.parse(readFileSync(backupPath, "utf8")).devices).toHaveLength(2);
  await closeDialog(page);
  await openDetail(page, "主力手机");
  await page.getByRole("button", { name: "删除设备", exact: true }).click();
  await page.getByRole("button", { name: "保留设备" }).click();
  await expect(page.getByRole("heading", { name: "主力手机", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "删除设备", exact: true }).click();
  await page.getByRole("button", { name: "确认删除" }).click();
  await expect(page.getByRole("button", { name: "查看 主力手机" })).toHaveCount(0);
  await page.reload();
  await expect(page.getByTestId("reference-total")).toContainText("等待第一笔估值");
  await page.getByRole("button", { name: "设置与备份", exact: true }).click();
  await page.locator('input[type="file"]').setInputFiles(backupPath);
  await expect(page.getByText(/已检查备份：2 件设备、1 条估值/)).toBeVisible();
  await page.getByRole("button", { name: "确认替换当前记录" }).click();
  await closeDialog(page);
  await expect(page.getByRole("button", { name: "查看 主力手机" })).toBeVisible();
  expect(errors).toEqual([]);
});

