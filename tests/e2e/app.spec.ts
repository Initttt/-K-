test("AI成功响应只预填明确字段，补全并确认后才保存（模拟网络响应）", async ({ page }) => {
  let requestBody: unknown;
  await page.route("**/api/ai/extract", async route => {
    if (route.request().method() === "GET") return route.fulfill({ json: { configured: true } });
    requestBody = route.request().postDataJSON();
    await route.fulfill({ json: { device: { name: "手机", category: "phone", brand: null, model: "测试X", configuration: "256GB", purchaseDate: null, purchaseDateText: "2026年5月", purchasePrice: 8000, notes: null } } });
  });
  await page.goto("/");
  await page.getByRole("button", { name: "添加设备", exact: true }).click();
  await page.getByRole("button", { name: "一句话录入", exact: true }).click();
  const text = "我在2026年5月花8000元买了一部手机，型号是测试X，容量256GB。";
  await page.getByLabel("描述你的设备").fill(text);
  await page.getByRole("button", { name: "提取并填写表单" }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByLabel("型号")).toHaveValue("测试X");
  await expect(dialog.getByLabel("品牌")).toHaveValue("");
  await expect(dialog.getByLabel("购买日期")).toHaveValue("");
  await expect(dialog.getByText(/请补充具体日期/)).toBeVisible();
  expect(requestBody).toEqual({ text, currency: "CNY" });
  expect(await page.evaluate(() => localStorage.getItem("my-gear:v1:personal:CN:CNY"))).toBeNull();
  await dialog.getByLabel("品牌").fill("测试品牌");
  await dialog.getByLabel("购买日期").fill("2026-05-10");
  await dialog.getByRole("button", { name: "确认并添加设备" }).click();
  await expect(page.getByRole("button", { name: "查看 手机", exact: true })).toBeVisible();
});
